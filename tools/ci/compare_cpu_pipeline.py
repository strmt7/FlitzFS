#!/usr/bin/env python3
"""Bounded hosted-CI comparison; synthetic throughput is not product qualification."""

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import resource
import shutil
import statistics
import subprocess
import tempfile
import time

MIB = 1024 * 1024
BASELINE = "2cf06327c6d71ebdfe90aadbed9187f8921a7267"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline", required=True, type=Path)
    parser.add_argument("--candidate", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    if os.environ.get("GITHUB_ACTIONS") != "true" or os.environ.get("RUNNER_ENVIRONMENT") != "github-hosted":
        raise RuntimeError("This comparison runs only on disposable GitHub-hosted runners")
    resource.setrlimit(resource.RLIMIT_AS, (256 * MIB, 256 * MIB))

    def child_limits():
        resource.setrlimit(resource.RLIMIT_AS, (128 * MIB, 128 * MIB))
        resource.setrlimit(resource.RLIMIT_CPU, (8, 8))
        resource.setrlimit(resource.RLIMIT_FSIZE, (16 * MIB, 16 * MIB))

    executables = {"baseline": args.baseline.resolve(strict=True), "candidate": args.candidate.resolve(strict=True)}
    started = time.monotonic()
    root = Path(tempfile.mkdtemp(prefix="flitzfs-cpu-compare-"))
    owned = []

    def track(name):
        path = root / name
        owned.append(path)
        return path

    def invoke(executable, *arguments):
        if time.monotonic() - started > 120:
            raise TimeoutError("CPU comparison exceeded its 120-second total budget")
        before = time.perf_counter_ns()
        result = subprocess.run([str(executable), *map(str, arguments)], check=True,
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=15,
                                preexec_fn=child_limits)
        if len(result.stdout) + len(result.stderr) > 65536:
            raise RuntimeError("Unexpected comparison output volume")
        return (time.perf_counter_ns() - before) / 1e9

    results = []
    try:
        if shutil.disk_usage(root).free < 1024 * MIB + 128 * MIB:
            raise RuntimeError("Insufficient free space for the bounded comparison and reserve")
        # Eight MiB of deterministic synthetic bytes, never user-supplied input.
        pattern = (b"FlitzFS independent chunk CPU workspace.\n" * 512)
        compressible = (pattern * (8 * MIB // len(pattern) + 1))[:8 * MIB]
        # Hash-generated bytes provide deterministic high entropy without a PRNG dependency.
        noisy = hashlib.shake_256(b"FlitzFS CPU comparison synthetic noise").digest(8 * MIB)
        for kind, payload in (("text-pattern", compressible), ("hash-noise", noisy)):
            source = track(kind + ".input")
            with source.open("xb") as stream:
                stream.write(payload)
            digest = hashlib.sha256(payload).hexdigest()
            for chunk_kib in (4, 128, 1024):
                lanes = {name: {op: [] for op in ("pack", "verify", "probe", "extract")}
                         for name in executables}
                stored_bytes = {}
                # Warm both lanes, then retain six samples in alternating AB/BA order.
                # A pair's complete containers must match byte for byte, not just size.
                for trial in range(7):
                    pair = {}
                    order = ("baseline", "candidate") if trial % 2 == 0 else ("candidate", "baseline")
                    for name in order:
                        executable = executables[name]
                        container = track(f"{kind}-{chunk_kib}-{trial}-{name}.flfs")
                        restored = track(f"{kind}-{chunk_kib}-{trial}-{name}.restored")
                        timings = {"pack": invoke(executable, "pack", source, container,
                                                   "--chunk-kib", chunk_kib, "--max-mib", 8),
                                   "verify": invoke(executable, "verify", container, "--max-mib", 8),
                                   "probe": invoke(executable, "probe", container, 123, 4 * MIB),
                                   "extract": invoke(executable, "extract", container, restored, "--max-mib", 8)}
                        if hashlib.sha256(restored.read_bytes()).hexdigest() != digest:
                            raise RuntimeError("Nonidentical CPU extraction")
                        wire = container.read_bytes()
                        pair[name] = wire
                        stored_bytes[name] = len(wire)
                        if trial:
                            for operation, elapsed in timings.items():
                                lanes[name][operation].append(elapsed)
                        # Remove individually recorded files only inside our new fixture.
                        restored.unlink()
                        container.unlink()
                    if pair["baseline"] != pair["candidate"]:
                        raise RuntimeError("Candidate changed the baseline container bytes")
                if hashlib.sha256(source.read_bytes()).hexdigest() != digest:
                    raise RuntimeError("Source changed during comparison")
                results.append({"fixture": kind, "logical_bytes": len(payload), "sha256": digest,
                                "chunk_kib": chunk_kib, "container_bytes": stored_bytes,
                                "seconds": lanes,
                                "median_seconds": {name: {op: statistics.median(samples)
                                                           for op, samples in ops.items()}
                                                   for name, ops in lanes.items()}})
            source.unlink()
        document = {"experimental": True, "baseline_commit": BASELINE,
                    "candidate_commit": os.environ.get("GITHUB_SHA"),
                    "runner_os": platform.platform(), "cpu_count": os.cpu_count(),
                    "cpu_model": next((line.split(":", 1)[1].strip() for line in
                                       Path("/proc/cpuinfo").read_text().splitlines()
                                       if line.startswith("model name")), "unknown"),
                    "memory": [line for line in Path("/proc/meminfo").read_text().splitlines()
                               if line.startswith(("MemTotal:", "MemAvailable:"))],
                    "filesystem": subprocess.run(["df", "-T", str(root)], check=True,
                                                 capture_output=True, text=True, timeout=5).stdout,
                    "codec": "Both builds require and link the runner's same Zstandard library",
                    "limits": {"parent_address_space_mib": 256, "child_address_space_mib": 128,
                               "child_cpu_seconds": 8, "child_file_mib": 16,
                               "child_wall_seconds": 15, "total_admission_seconds": 120},
                    "scope": "Warm shared hosted runner; includes CLI startup, file I/O and flush; no cache eviction, GPU, power or real-world workload claims",
                    "elapsed_seconds": time.monotonic() - started, "results": results}
        with args.output.open("x", encoding="utf-8") as output:
            json.dump(document, output, indent=2)
            output.write("\n")
        print(json.dumps({"cases": len(results), "byte_parity": True,
                          "output": str(args.output), "elapsed_seconds": document["elapsed_seconds"]}))
    finally:
        for path in owned:
            path.unlink(missing_ok=True)
        root.rmdir()


if __name__ == "__main__":
    main()
